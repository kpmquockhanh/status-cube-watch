#!/usr/bin/env python3
"""Rasterise Inter (OFL) into anti-aliased VLW fonts for LovyanGFX.

The panel is only ~230 ppi, and the bundled Adafruit-GFX fonts are 1-bit, so
text shows stair-steps. VLW glyphs carry 8-bit alpha, which LovyanGFX blends
onto the sprite. Output: ../src/fonts_gen.h (arrays loaded by ui.cpp).

    python3 -m venv /tmp/fontvenv && /tmp/fontvenv/bin/pip install -r tools/requirements.txt
    /tmp/fontvenv/bin/python tools/gen_fonts.py

Pillow is pinned (tools/requirements.txt): its rasteriser moves glyph boxes and
ascent by a pixel between releases. 11.3.0 reproduces the committed b24, b18,
s12 and r17 byte-for-byte; no release reproduces b44, b36 and b30, so those
(FROZEN) are copied unchanged from the existing fonts_gen.h instead of redrawn.
"""
import re
import struct
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).parent
TTF = HERE / "Inter.ttf"
OUT = HERE.parent / "src" / "fonts_gen.h"

# name, weight, pixel size
FONTS = [
    ("b44", 700, 44), ("b36", 700, 36), ("b30", 700, 30), ("b24", 700, 24),
    ("b18", 700, 18), ("s12", 600, 13), ("r17", 400, 17),
    # Vietnamese street names: same faces as b18/s12 plus the letters below. They
    # are separate fonts because LovyanGFX takes a VLW's line height from its
    # tallest glyph, so stacked accents in b18/s12 would shift every ASCII
    # label drawn in them.
    ("b18v", 700, 18), ("s12v", 600, 13),
]
FROZEN = {"b44", "b36", "b30"}
ASCII = [chr(c) for c in range(0x20, 0x7F)]
# Street names on the navigation screen: Vietnamese letters plus the middle dot.
VIET = (list("ÀÁÂÃÈÉÊÌÍÒÓÔÕÙÚÝàáâãèéêìíòóôõùúýĂăĐđĨĩŨũƠơƯư\u00b7")
        + [chr(c) for c in range(0x1EA0, 0x1EFA)])
CHARSETS = {"b18v": ASCII + sorted(set(VIET)), "s12v": ASCII + sorted(set(VIET))}


def build(weight, size, chars):
    f = ImageFont.truetype(str(TTF), size)
    f.set_variation_by_axes([min(32, max(14, size)), weight])
    glyphs, bitmaps = [], []
    for ch in chars:
        adv = round(f.getlength(ch))
        l, t, r, b = f.getbbox(ch, anchor="ls")
        w, h = max(0, r - l), max(0, b - t)
        data = b""
        if ch != " " and w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-l, -t), ch, font=f, fill=255, anchor="ls")
            data = im.tobytes()
        else:
            w = h = 0
        glyphs.append((ord(ch), h, w, adv, -t if h else 0, l if w else 0))
        bitmaps.append(data)
    asc = -f.getbbox("d", anchor="ls")[1]
    desc = f.getbbox("p", anchor="ls")[3]
    out = struct.pack(">6i", len(glyphs), 11, size, 0, asc, desc)
    for g in glyphs:
        out += struct.pack(">7i", *g, 0)
    return out + b"".join(bitmaps)


def frozen_blobs():
    text = OUT.read_text()
    found = {}
    for m in re.finditer(r"font_(\w+)\[\] = \{(.*?)\};", text, re.S):
        if m.group(1) in FROZEN:
            found[m.group(1)] = m.group(2).strip()
    if set(found) != FROZEN:
        sys.exit("fonts_gen.h lacks the frozen fonts %s" % sorted(FROZEN))
    return found


keep = frozen_blobs()
with OUT.open("w") as fh:
    fh.write("#pragma once\n// Generated by tools/gen_fonts.py (Inter, SIL OFL). Do not edit.\n"
             "#include <stdint.h>\n")
    for name, wt, sz in FONTS:
        fh.write(f"static const uint8_t font_{name}[] = {{\n")
        if name in FROZEN:
            print(name, "kept")
            fh.write(keep[name] + "\n};\n")
            continue
        blob = build(wt, sz, CHARSETS.get(name, ASCII))
        print(name, len(blob), "bytes")
        for i in range(0, len(blob), 24):
            fh.write(",".join(str(x) for x in blob[i:i + 24]) + ",\n")
        fh.write("};\n")
